#!/usr/bin/env python3
"""Download Google Fonts (latin + latin-ext woff2) and generate css/fonts.css."""
import re, subprocess, os, sys

FAMS = [
    "Inter:wght@400;700",
    "Roboto:wght@400;700",
    "Montserrat:wght@400;700",
    "Poppins:wght@400;700",
    "Open+Sans:wght@400;700",
    "Lato:wght@400;700",
    "Oswald:wght@400;700",
    "Raleway:wght@400;700",
    "Merriweather:wght@400;700",
    "Playfair+Display:wght@400;700",
    "Nunito:wght@400;700",
    "Fira+Sans:wght@400;700",
    "JetBrains+Mono:wght@400;700",
    "Caveat:wght@400;700",
]
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, "fonts")
CSS_PATH = os.path.join(ROOT, "css", "fonts.css")
os.makedirs(FONT_DIR, exist_ok=True)

url = "https://fonts.googleapis.com/css2?" + "&".join("family=" + f for f in FAMS) + "&display=swap"
css = subprocess.run(["curl", "-s", "-m", "30", "-A", UA, url], capture_output=True, text=True).stdout
if "@font-face" not in css:
    print("FAILED to fetch css:", css[:300]); sys.exit(1)

block_re = re.compile(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{[^}]+\})")
faces = []
seen = set()
for subset, block in block_re.findall(css):
    if subset not in ("latin", "latin-ext"):
        continue
    fam = re.search(r"font-family:\s*'([^']+)'", block).group(1)
    weight = re.search(r"font-weight:\s*(\d+)", block).group(1)
    style = re.search(r"font-style:\s*(\w+)", block).group(1)
    src = re.search(r"url\((https://[^)]+)\)", block).group(1)
    urange = re.search(r"unicode-range:\s*([^;]+);", block)
    slug = fam.replace(" ", "")
    fname = f"{slug}-{weight}-{subset}.woff2"
    key = (fam, weight, style, subset)
    if key in seen:
        continue
    seen.add(key)
    path = os.path.join(FONT_DIR, fname)
    if not os.path.exists(path):
        r = subprocess.run(["curl", "-s", "-L", "-m", "30", "-A", UA, "-o", path, src])
        if r.returncode != 0 or not os.path.exists(path) or os.path.getsize(path) < 500:
            print("dl failed:", fname); sys.exit(1)
    face = [f"@font-face {{\n  font-family: '{fam}';", f"  font-style: {style};",
            f"  font-weight: {weight};", "  font-display: swap;",
            f"  src: url('../fonts/{fname}') format('woff2');"]
    if urange:
        face.append(f"  unicode-range: {urange.group(1).strip()};")
    face.append("}")
    faces.append("\n".join(face))

with open(CSS_PATH, "w") as f:
    f.write("/* Local Google Fonts — offline, no CDN. Generated by tools/fetch_fonts.py */\n")
    f.write("\n".join(faces) + "\n")

total = sum(os.path.getsize(os.path.join(FONT_DIR, f)) for f in os.listdir(FONT_DIR))
print(f"faces: {len(faces)}, files: {len(os.listdir(FONT_DIR))}, total: {total//1024} KB")
